/** ZLB（Zero-Length Body）確認応答メッセージを作るヘルパー */
function zlb(id: string, phase: string, ns: number, nr: number, ackOf: string): Step {
  return {
    id,
    from: 'lns',
    to: 'lac',
    message: 'ZLB (ACK)',
    phase,
    look: { color: C.ack, accessory: 'check' },
    summary: `${ackOf} の受信確認（ZLB）`,
    kidTitle: 'うけとったよ！',
    kid: `「${ackOf} を ちゃんと うけとったよ！」と へんじだけを する、なかみが からっぽの おてがみだよ。`,
    detail: `AVP を持たない制御メッセージで、${ackOf} の受信確認だけを行う。ZLB は自分の Ns を進めない。Nr は「次に受け取りたい Ns」を表す。`,
    fields: [
      { name: 'ヘッダー', value: `T=1, L=1, S=1, Ns=${ns}, Nr=${nr}` },
      { name: 'AVP', value: 'なし（ボディ長 0）' },
    ],
    rfc: [{ rfc: 2661, section: '5.8' }],
  };
}

